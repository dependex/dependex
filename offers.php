let currentTier = { key: 'starter', name: 'Starter Kit', price: 27 };

function selectTier(name, price, key = 'starter') {
  currentTier = { name, price, key };
  document.getElementById('modalTierName').textContent = name;
  document.getElementById('modalTierPrice').textContent = '€ ' + price;
  const m = document.getElementById('checkoutModal');
  m.style.display = 'block';
  m.classList.add('show');
}

function closeModal() {
  const m = document.getElementById('checkoutModal');
  m.style.display = 'none';
  m.classList.remove('show');
}

function toggleFaq(btn) {
  const body = btn.nextElementSibling;
  const isShown = body.style.display === 'block';
  document.querySelectorAll('.epppa-body').forEach(el => el.style.display = 'none');
  body.style.display = isShown ? 'none' : 'block';
}

async function submitOrder(e) {
  e.preventDefault();
  const name = document.getElementById('orderName').value.trim();
  const email = document.getElementById('orderEmail').value.trim();
  const method = document.getElementById('orderMethod').value;
  const btn = e.target.querySelector('button[type="submit"]');

  btn.disabled = true;
  const originalText = btn.textContent;
  btn.textContent = 'Elaborazione Ordine in corso...';

  try {
    const res = await fetch('/api/orders.php', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        tier: currentTier.key,
        name: name,
        email: email,
        payment_method: method
      })
    });

    const data = await res.json();
    if (data.success && data.redirect_url) {
      window.location.href = data.redirect_url;
    } else {
      alert('Impossibile completare la richiesta: ' + (data.error || 'Riprova più tardi.'));
      btn.disabled = false;
      btn.textContent = originalText;
    }
  } catch (err) {
    alert('Errore di connessione con il server ordini. Controlla la tua connessione e riprova.');
    btn.disabled = false;
    btn.textContent = originalText;
  }
}
